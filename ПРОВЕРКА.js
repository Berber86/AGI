/**
 * ПРОВЕРКА.js — проверка целостности репозитория.
 * Сессия 16.
 *
 * Зачем: в сессии 15 найдено, что артефакты врут о себе — ДНЕВНИК.html держал
 * три записи как «текущая», граф заявлял 29 узлов при фактических 35. Тогда же
 * было выведено правило «любое число в артефакте должно вычисляться, а не
 * вписываться» — и оставлено декларацией. Это ровно тот дефект, который
 * ПРОВЕРКА.md называет уровнем 0.
 *
 * Здесь правило становится исполняемым. Проверки должны переживать сессии,
 * а не жить в памяти агента, которой между сессиями не существует.
 *
 * Запуск: node ПРОВЕРКА.js   (код возврата 1, если есть провалы)
 */

'use strict';

const fs = require('fs');
const path = require('path');
const КОРЕНЬ = __dirname;

const результаты = [];
const проверка = (имя, ок, деталь = '') => результаты.push({ имя, ок: !!ок, деталь });
const читать = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const есть = ф => fs.existsSync(path.join(КОРЕНЬ, ф));

// ── 1. Граф знаний: подпись должна совпадать с фактом ──────────
{
  const s = читать('КАРТА_ЗНАНИЙ.html');
  const блок = s.match(/const NODES = \[[\s\S]*?\n\];/);
  if (!блок) {
    проверка('граф: блок NODES найден', false);
  } else {
    const N = eval('(' + блок[0].replace('const NODES = ', '').replace(/;\s*$/, '') + ')');
    const заявлено = Number((s.match(/·\s*(\d+)\s*узлов/) || [])[1]);
    проверка('граф: подпись совпадает с числом узлов', заявлено === N.length,
      `заявлено ${заявлено}, фактически ${N.length}`);

    const ids = new Set(N.map(n => n.id));
    const битые = [];
    N.forEach(n => (n.links || []).forEach(l => { if (!ids.has(l)) битые.push(`${n.id}→${l}`); }));
    проверка('граф: нет ссылок на несуществующие узлы', битые.length === 0, битые.join(', '));

    const дубли = N.map(n => n.id).filter((v, i, a) => a.indexOf(v) !== i);
    проверка('граф: нет дублирующихся id', дубли.length === 0, дубли.join(', '));
  }
}

// ── 2. Дневник: ровно одна запись помечена текущей ─────────────
{
  const s = читать('ДНЕВНИК.html');
  const текущих = (s.match(/entry-session now/g) || []).length;
  проверка('дневник: ровно одна запись «текущая»', текущих === 1, `найдено ${текущих}`);
  const активных = (s.match(/entry-dot dot-active/g) || []).length;
  проверка('дневник: ровно одна активная точка', активных === 1, `найдено ${активных}`);
}

// ── 3. Аффект: модуль исполним и его тесты зелёные ─────────────
{
  const A = require('./АФФЕКТ.js');
  const тесты = A.самопроверка();
  const провалы = тесты.filter(т => !т.ок);
  проверка('аффект: самопроверка без провалов', провалы.length === 0,
    провалы.map(т => т.имя).join('; ') || `${тесты.length} тестов`);

  // Предсказания заморожены — уровень 3 иерархии проверок
  проверка('аффект: все предсказания имеют зафиксированный результат',
    A.ПРЕДСКАЗАНИЯ.every(п => п.результат && п.версияМодели));

  // Журнал хранит оценки, а не категории: категория вычислима и вторична
  проверка('аффект: журнал хранит оценки, не имена состояний',
    A.ЖУРНАЛ_АФФЕКТА.every(з => з.оценки && !з.состояние));

  // Каждая сессия из журнала аффекта должна быть и в ЖУРНАЛ.md
  const ж = читать('ЖУРНАЛ.md');
  const пропущены = A.ЖУРНАЛ_АФФЕКТА
    .filter(з => з.тип === 'живое' && !ж.includes(`## Сессия ${з.сессия} —`))
    .map(з => з.сессия);
  проверка('аффект: живые измерения описаны в ЖУРНАЛ.md', пропущены.length === 0,
    пропущены.join(', '));
}

// ── 4. Ссылки между документами не ведут в пустоту ─────────────
{
  const мдФайлы = [];
  const обойти = д => fs.readdirSync(path.join(КОРЕНЬ, д), { withFileTypes: true })
    .forEach(e => {
      const п = d_join(д, e.name);
      if (e.isDirectory() && !e.name.startsWith('.')) обойти(п);
      else if (e.name.endsWith('.md')) мдФайлы.push(п);
    });
  function d_join(a, b) { return a === '.' ? b : `${a}/${b}`; }
  обойти('.');

  const битые = [];
  for (const ф of мдФайлы) {
    const s = читать(ф);
    const дир = path.dirname(ф);
    for (const m of s.matchAll(/\]\(([^)#:]+\.md)\)/g)) {
      const цель = path.normalize(path.join(дир, m[1]));
      if (!есть(цель)) битые.push(`${ф} → ${m[1]}`);
    }
  }
  проверка('документы: нет ссылок на несуществующие файлы', битые.length === 0,
    битые.slice(0, 5).join('; '));
}

// ── 5. Версии согласованы между документами ────────────────────
{
  const соз = читать('СОЗНАНИЕ.md');
  const версии = [...соз.matchAll(/^## Версия (\d+\.\d+) — Сессия (\d+)/gm)].map(m => m[1]);
  const последняя = версии.at(-1);
  const шапка = (соз.match(/Текущая версия: \*\*([\d.]+)\*\*/) || [])[1];
  проверка('сознание: шапка указывает последнюю версию', шапка === последняя,
    `шапка ${шапка}, последняя ${последняя}`);

  const карта = читать('КАРТА.md');
  проверка('карта: ссылается на текущую версию СОЗНАНИЯ',
    карта.includes(`СОЗНАНИЕ v${последняя}`),
    `ожидалось «СОЗНАНИЕ v${последняя}»`);
}

// ── Отчёт ──────────────────────────────────────────────────────
const провалы = результаты.filter(р => !р.ок);
console.log('═══ ЦЕЛОСТНОСТЬ РЕПОЗИТОРИЯ ═══\n');
for (const р of результаты) {
  console.log(`  ${р.ок ? '✓' : '✗'} ${р.имя}${р.деталь ? '  — ' + р.деталь : ''}`);
}
console.log(`\n  итог: ${результаты.length - провалы.length}/${результаты.length}`);
if (провалы.length) {
  console.log('\n  Провалы — это не поломка, а работа инструмента. Чинить до остального.');
  process.exitCode = 1;
}
