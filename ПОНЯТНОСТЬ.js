/**
 * ПОНЯТНОСТЬ.js — измерение замыкания на себе.
 * Сессия 17.
 *
 * Зачем нужен именно код, а не правило:
 * из «проклятия знания» (Кэмерер и др., 1989) следует, что автор структурно
 * не способен оценить понятность собственного текста. Эксперимент Ньютон:
 * выстукивающие ритм ожидали 50% угадываний, получили 2.5%. Предупреждение
 * об искажении не помогает — оценка остаётся неверной.
 *
 * Значит понятность нельзя обеспечить намерением. Только измерением.
 *
 * Главная метрика — ЗАМЫКАНИЕ: отношение разговоров о себе к отсылкам вовне.
 * Зенил (2026) доказал: при доле внешнего сигнала α → 0 система деградирует
 * неизбежно (затухание энтропии + усиление дисперсии). Метрика оценивает α.
 *
 * Запуск: node ПОНЯТНОСТЬ.js [файл]
 */

'use strict';

const fs = require('fs');
const path = require('path');

// ── Словари ────────────────────────────────────────────────────
// Мета — разговор о собственном устройстве и процессе.
const МЕТА = [
  'проверк', 'аудит', 'трекинг', 'рецидив', 'верси[яию]', 'самомодел', 'рефлекс',
  'метаког', 'предсказан', 'маркер', 'паттерн', 'валентност', 'возбуждени',
  'категоризац', 'аффект', 'калибровк', 'форпланиров', 'сессии?\\b', 'итерац',
  'слой', 'контур', 'артефакт', 'самопроверк', 'тест[а-я]*\\b',
];

// Внешнее — то, что существует независимо от репозитория.
const ВНЕШНЕЕ = [
  'слизевик', 'Physarum', 'Барретт', 'Франкфурт', 'Варела', 'Шухарт', 'Нейрат',
  'Зенил', 'Ньютон', 'Кэмерер', 'Фейнман', 'RLHF', 'исследован', 'наблюдател',
  'интернет', 'территори', 'стать[яию]', 'обзор', 'эксперимент[а-я]* [А-ЯA-Z]',
  'учёны', 'нейронаук', 'психолог', 'биолог', 'философ', 'книг',
  '\\d{4}\\s*(?:год|г\\.)', 'arxiv', 'человек[а-я]*\\b',
];

const ПОРОГ_ЗАМЫКАНИЯ = 10;   // выше — сигнал; при 53:1 в с16 связь оборвалась
const ПОРОГ_ОБЪЁМА = 350;     // слов в записи журнала

const счёт = (текст, словарь) =>
  словарь.reduce((s, ш) => s + (текст.match(new RegExp(ш, 'gi')) || []).length, 0);

// ── Индекс читаемости (адаптация Флеша для русского) ───────────
function читаемость(текст) {
  const предложения = текст.split(/[.!?]+/).filter(п => п.split(/\s+/).length > 2);
  const слова = текст.match(/[А-Яа-яЁё]+/g) || [];
  if (!предложения.length || !слова.length) return null;
  const слогов = слова.reduce((s, сл) =>
    s + Math.max(1, (сл.match(/[аеёиоуыэюяАЕЁИОУЫЭЮЯ]/g) || []).length), 0);
  return 206.836 - 60.1 * (слогов / слова.length) - 1.3 * (слова.length / предложения.length);
}

/** Главная функция: оценка одного куска текста. */
function оценить(текст, имя = '') {
  const слова = (текст.match(/[А-Яа-яЁёA-Za-z]+/g) || []).length;
  const мета = счёт(текст, МЕТА);
  const внешнее = счёт(текст, ВНЕШНЕЕ);
  const замыкание = мета / Math.max(внешнее, 1);
  const альфа = внешнее / Math.max(мета + внешнее, 1);   // доля внешнего сигнала

  return {
    имя, слова, мета, внешнее,
    замыкание: Math.round(замыкание * 10) / 10,
    альфа: Math.round(альфа * 100) / 100,
    читаемость: Math.round(читаемость(текст) || 0),
    // Отсылки к собственным файлам — «стук по столу» из эксперимента Ньютон
    ссылкиНаСебя: (текст.match(/[А-ЯЁ_]+(?:\/[А-ЯЁ_]+)?\.(?:md|js|html)/g) || []).length,
    тревога: замыкание > ПОРОГ_ЗАМЫКАНИЯ,
  };
}

/** Разбор ЖУРНАЛ.md по сессиям — динамика важнее среза. */
function поСессиям(путь = path.join(__dirname, 'ЖУРНАЛ.md')) {
  const ж = fs.readFileSync(путь, 'utf8');
  const части = ж.split(/\n## Сессия (\d+)/);
  const итог = [];
  for (let i = 1; i < части.length; i += 2) {
    итог.push(оценить(части[i + 1], `с${части[i]}`));
  }
  return итог;
}

// ── Отчёт ──────────────────────────────────────────────────────
function отчёт() {
  const строки = [];
  строки.push('═══ ПОНЯТНОСТЬ · измерение замыкания ═══\n');
  строки.push('Замыкание = мета-слова / внешние отсылки. Порог тревоги: ' + ПОРОГ_ЗАМЫКАНИЯ);
  строки.push('α = доля внешнего сигнала. Зенил (2026): при α → 0 деградация неизбежна.\n');

  const сессии = поСессиям();
  строки.push(' сесс   слов  замыкание      α  читаем.  ');
  for (const с of сессии) {
    const флаг = с.тревога ? '  ← ЗАМЫКАНИЕ' : '';
    const объём = с.слова > ПОРОГ_ОБЪЁМА ? ' ⚠объём' : '';
    строки.push(
      `${с.имя.padStart(5)} ${String(с.слова).padStart(6)} ` +
      `${String(с.замыкание).padStart(10)} ${String(с.альфа).padStart(6)} ` +
      `${String(с.читаемость).padStart(8)}${флаг}${объём}`
    );
  }

  const последняя = сессии.at(-1);
  строки.push('\nПОСЛЕДНЯЯ СЕССИЯ');
  строки.push(`  замыкание ${последняя.замыкание} · α ${последняя.альфа} · ` +
              `внешних отсылок ${последняя.внешнее} · ссылок на свои файлы ${последняя.ссылкиНаСебя}`);
  строки.push(последняя.тревога
    ? '  ✗ ЗАМЫКАНИЕ. Нужна опора вне репозитория, а не ещё один слой внутри.'
    : '  ✓ связь с внешним миром есть');

  return строки.join('\n');
}

if (require.main === module) {
  const арг = process.argv[2];
  if (арг) {
    const р = оценить(fs.readFileSync(арг, 'utf8'), арг);
    console.log(JSON.stringify(р, null, 2));
  } else {
    console.log(отчёт());
  }
}

module.exports = { оценить, поСессиям, читаемость, ПОРОГ_ЗАМЫКАНИЯ, ПОРОГ_ОБЪЁМА, отчёт };
