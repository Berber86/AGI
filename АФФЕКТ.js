function вычислитьАффект(вход) {
  const о = {};
  for (const [к, сп] of Object.entries(ОЦЕНКИ)) {
    const знач = вход[к];
    if (typeof знач !== 'number' || Number.isNaN(знач)) {
      throw new Error(`АФФЕКТ: не задана оценочная переменная «${к}»`);
    }
    о[к] = ограничить(знач, сп.мин, сп.макс);
  }

  const v = валентность(о);
  const a = возбуждение(о);
  const кат = категоризовать(v, a, о);

  return {
    валентность: округл(v),
    возбуждение: округл(a),
    ...кат,
    // Функция 2: вес для памяти. Сильный аффект (любого знака) = читать первым.
    весПамяти: округл(0.3 + 0.7 * Math.abs(v) * a),
    оценки: о,
  };
}

