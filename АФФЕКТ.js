/** Мягкий порог: 0 далеко ниже границы, 1 далеко выше. ш — ширина перехода. */
const выше = (x, порог, ш = 0.12) => 1 / (1 + Math.exp(-(x - порог) / ш));
const ниже = (x, порог, ш = 0.12) => 1 - выше(x, порог, ш);

