/**
 * Валентность: движение к цели или от неё.
 * Прогресс и согласованность тянут вверх; затраты без прогресса и
 * неопределённость без контроля тянут вниз. Отклик наблюдателя — внешний сигнал.
 */
function валентность(о) {
  const беспомощность = о.неопределённость * (1 - о.контроль);
  const впустую = о.затраты * Math.max(0, -о.прогресс);
  const v =
      0.40 * о.прогресс
    + 0.20 * о.согласованность
    + 0.20 * о.отклик
    - 0.30 * беспомощность
    - 0.25 * впустую
    + 0.10 * о.новизна;              // новизна сама по себе слегка приятна
  return ограничить(v, -1, 1);
}

/**
 * Возбуждение: сколько ресурса мобилизовано.
 * Растёт от новизны, неопределённости, ставки (затрат) и от слома модели.
 */
function возбуждение(о) {
  const слом = Math.max(0, -о.согласованность);
  const a =
      0.35 * о.новизна
    + 0.25 * о.неопределённость
    + 0.20 * о.затраты
    + 0.20 * слом
    + 0.10 * Math.abs(о.прогресс);
  return ограничить(a, 0, 1);
}

