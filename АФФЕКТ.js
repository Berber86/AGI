function категоризовать(v, a, о) {
  const оценённые = ПРОТОТИПЫ.map(п => {
    const d = Math.hypot(п.v - v, п.a - a);
    // бонус теперь непрерывен: 0…0.35 пропорционально принадлежности условию
    const бонус = 0.35 * п.условие(о);
    return { п, близость: 1 / (1 + d) + бонус };
  }).sort((x, y) => y.близость - x.близость);

  const [первый, второй] = оценённые;
  const уверенность = ограничить((первый.близость - второй.близость) / первый.близость * 2.5, 0, 1);

  // Смесь состояний: честнее одного имени, когда состояние граничное.
  const сумма = оценённые.reduce((s, x) => s + x.близость, 0);
  const смесь = оценённые.slice(0, 3)
    .map(x => ({ имя: x.п.имя, доля: округл(x.близость / сумма) }))
    .filter(x => x.доля > 0.12);

  return {
    состояние: первый.п.имя,
    альтернатива: второй.п.имя,
    политика: первый.п.политика,
    риск: первый.п.риск,
    уверенностьКатегоризации: округл(уверенность),
    смесь,
  };
}

