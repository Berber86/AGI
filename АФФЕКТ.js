function приоритетПамяти(журнал = ЖУРНАЛ_АФФЕКТА) {
  return журнал
    .map(з => ({ сессия: з.сессия, событие: з.событие, ...вычислитьАффект(з.оценки) }))
    .sort((a, b) => b.весПамяти - a.весПамяти)
    .map(з => ({ сессия: з.сессия, вес: з.весПамяти, состояние: з.состояние, событие: з.событие }));
}

