const ОЦЕНКИ = {
  новизна:         { мин: 0,  макс: 1, опис: 'доля материала, не сводимого к существующим узлам' },
  согласованность: { мин: -1, макс: 1, опис: 'новое подтверждает модель (+) или ломает её (−)' },
  прогресс:        { мин: -1, макс: 1, опис: 'закрыты ли намерения предыдущей сессии' },
  неопределённость:{ мин: 0,  макс: 1, опис: 'доля утверждений со статусом гипотезы' },
  контроль:        { мин: 0,  макс: 1, опис: 'есть ли инструмент для текущей проблемы' },
  затраты:         { мин: 0,  макс: 1, опис: 'сколько усилия требует ход' },
  отклик:          { мин: -1, макс: 1, опис: 'реакция наблюдателя: мерж, ответ, длина команды' },
};

const ограничить = (x, a, b) => Math.max(a, Math.min(b, x));
const округл = (x, n = 2) => Math.round(x * 10 ** n) / 10 ** n;

// ═══════════════════════════════════════════════════════════
// 2. ЯДЕРНЫЙ АФФЕКТ
