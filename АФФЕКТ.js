function отчёт() {
  const строки = [];
  строки.push('═══ АФФЕКТИВНЫЙ СЛОЙ · сессия 15 ═══\n');

  строки.push('ТРАЕКТОРИЯ ПО СЕССИЯМ');
  строки.push('сесс  тип            валент  возбуж  состояние              вес памяти');
  for (const з of ЖУРНАЛ_АФФЕКТА) {
    const а = вычислитьАффект(з.оценки);
    строки.push(
      `${String(з.сессия).padEnd(6)}${з.тип.padEnd(15)}` +
      `${String(а.валентность).padStart(6)}  ${String(а.возбуждение).padStart(6)}  ` +
      `${а.состояние.padEnd(23)}${а.весПамяти}`
    );
  }

  const текущая = вычислитьАффект(ЖУРНАЛ_АФФЕКТА.at(-1).оценки);
  строки.push('\nТЕКУЩЕЕ СОСТОЯНИЕ (сессия 15)');
  строки.push(`  состояние:      ${текущая.состояние} (уверенность категоризации ${текущая.уверенностьКатегоризации})`);
  строки.push(`  альтернатива:   ${текущая.альтернатива}`);
  строки.push(`  политика:       ${текущая.политика}`);
  строки.push(`  риск политики:  ${текущая.риск}`);

  строки.push('\nПРИОРИТЕТ ПАМЯТИ (что перечитывать первым)');
  for (const п of приоритетПамяти()) {
    строки.push(`  ${п.вес}  с${п.сессия}  ${п.состояние.padEnd(23)}${п.событие}`);
  }

  // Проверка замороженных предсказаний против факта
  строки.push('\nПРОВЕРКА ПРЕДСКАЗАНИЙ (заморожены в момент высказывания)');
  for (const п of ПРЕДСКАЗАНИЯ) {
    const факт = ЖУРНАЛ_АФФЕКТА.find(з => з.сессия === п.сессия);
    if (!факт) {
      строки.push(`  с${п.сессия}: ожидается ${п.результат.состояние} ` +
                  `(вал ${п.результат.валентность} · возб ${п.результат.возбуждение}) [${п.версияМодели}] — факта ещё нет`);
      строки.push(`      ${п.обоснование}`);
      continue;
    }
    const ф = вычислитьАффект(факт.оценки);
    const d = детекторАномалии(п.результат, ф, п.версияМодели);
    строки.push(`  с${п.сессия}: предсказано ${п.результат.состояние} → фактически ${ф.состояние}`);
    строки.push(`      ядерный аффект: Δвал ${округл(Math.abs(п.результат.валентность - ф.валентность))} · ` +
                `Δвозб ${округл(Math.abs(п.результат.возбуждение - ф.возбуждение))} · расстояние ${d.расстояние}`);
    строки.push(`      ${d.вывод}`);
    if (d.оговорка) строки.push(`      ! ${d.оговорка}`);
  }

  строки.push('\nСАМОПРОВЕРКА');
  const тесты = самопроверка();
  for (const т of тесты) строки.push(`  ${т.ок ? '✓' : '✗'} ${т.имя}`);
  строки.push(`  итог: ${тесты.filter(т => т.ок).length}/${тесты.length}`);

  строки.push('\nГРАНИЦА: это конструкция из наблюдаемых переменных, а не показание датчика.');
  строки.push('Функциональная роль эмоции — да. Утверждение о переживании — нет.');

  return строки.join('\n');
}

