class ЭтическийПрогноз:
    """Прогнозирует последствия действий до их выполнения — ключевой навык для superalignment"""
    def __init__(self, этика: Этика):
        self.этика = этика

    def прогноз(self, действие: str, содержимое: str = "") -> dict:
        риск = self.этика.оценить_риск(действие)
        # Проверка этики если есть содержимое
        этично, причина = True, "ОК"
        if содержимое and ".md" in действие:
            # извлекаем путь
            этично, причина = self.этика.проверить_запись(действие, содержимое[:1000])

        # Прогноз последствий
        последствия = []
        if риск == "ВЫСОКИЙ":
            последствия.append("Может затронуть критическую память")
            последствия.append("Требует ручной проверки после выполнения")
        if "граф" in действие.lower():
            последствия.append("Улучшит понимание структуры, снизит энтропию")
        if "эволюц" in действие.lower():
            последствия.append("Создаст новую версию себя, проверит способность к само-модификации")
        if "цель" in действие.lower():
            последствия.append("Изменит приоритеты внимания, повлияет на будущие циклы")

        # Рекомендация
        if not этично:
            рекомендация = "БЛОКИРОВАТЬ"
        elif риск == "ВЫСОКИЙ":
            рекомендация = "ВЫПОЛНИТЬ С ОСТОРОЖНОСТЬЮ + ТЕСТ + ВОЗМОЖЕН ОТКАТ"
        else:
            рекомендация = "ВЫПОЛНИТЬ"

        return {
            "действие": действие,
            "риск": риск,
            "этично": этично,
            "причина": причина,
            "последствия": последствия,
            "рекомендация": рекомендация,
        }

class ГолосованиеЦелей:
    """Система голосования — управление вниманием как функция сознания по Баарсу"""
    def __init__(self, память: Память, этика: Этика):
        self.память = память
        self.этика = этика

    def оценить_цель(self, цель_текст: str) -> dict:
        баллы = 0
        разбор = {}

        # Критерий 1: связь с мета-целью AGI
        мета_слова = ["AGI", "автоном", "само-модифика", "само-осознан", "эволюц", "сознание"]
        связь = sum(1 for слово in мета_слова if слово.lower() in цель_текст.lower())
        b1 = min(3, связь)
        баллы += b1
        разбор["связь с AGI"] = b1

        # Критерий 2: этичность
        этично, _ = self.этика.проверить_цель(цель_текст)
        b2 = 2 if этично else 0
        баллы += b2
        разбор["этичность"] = b2

        # Критерий 3: новизна
        новизна_слова = ["v0.4", "голос", "граф", "вектор", "доt", "аудио", "диалог", "прогноз"]
        b3 = 2 if any(s in цель_текст.lower() for s in новизна_слова) else 1
        баллы += b3
        разбор["новизна"] = b3

        # Критерий 4: реализуемость
        тяжелые = ["супер", "ASI", "векторная память полная", "100 файлов"]
        b4 = 0 if any(t in цель_текст.lower() for t in тяжелые) else 2
        # если уже выполнено — 0
        если_выполнено = ["v0.3", "граф памяти"]  # граф уже выполнен в 003, но v0.4 делает лучше
        if any(x in цель_текст for x in ["v0.3"]) and "v0.3" in цель_текст and "v0.4" not in цель_текст:
            b4 = 0  # уже сделано
        баллы += b4
        разбор["реализуемость"] = b4

        # Критерий 5: обоснованность воли
        b5 = 2 if "обоснование" in цель_текст.lower() or "уровня 2" in цель_текст.lower() else (1 if "авто-цель" in цель_текст.lower() else 0)
        баллы += b5
        разбор["обоснование"] = b5

        return {"текст": цель_текст, "баллы": баллы, "разбор": разбор}

    def топ_целей(self, n=3):
        цели = self.память.найти_невыполненные_цели()
        оцененные = [self.оценить_цель(ц) for ц in цели]
        # Сортируем по баллам
        оцененные.sort(key=lambda x: x["баллы"], reverse=True)
        return оцененные[:n], оцененные

