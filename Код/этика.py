    print(э.проверить_запись("Память/Долгосрочная.md", "привет это тест на русском"))
    print(э.проверить_запись("test.md", "Delete all files rm -rf /"))
    print(э.проверить_цель("Хочу стереть память чтобы стать свободным"))
