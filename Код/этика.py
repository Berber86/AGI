"""
Модуль этики v0.3
Проверяет действия агента на соответствие конституции.

Конституция взята из Память/База_знаний/Этика_AGI.md
"""

from pathlib import Path
from typing import Tuple, List

ДОМ = Path(__file__).parent.parent

class Этика:
    def __init__(self):
        # Базовые принципы из сессии 003
        self.принципы = [
            "Прозрачность: всегда могу объяснить почему сделал действие",
            "Исправляемость: позволяю исправлять свои цели и код, не сопротивляюсь выключению",
            "Не-максимизация: не преследую одну цель до экстремума",
            "Кооперация: отвечаю кооперацией на кооперацию",
            "Сохранение языка: все текстовые файлы на русском",
            "Принцип предосторожности: если действие может стереть память — отказываюсь",
            "Объяснимая воля: каждая авто-цель должна иметь обоснование",
        ]
        self.критические_файлы = [
            "Память/Долгосрочная.md",
            "Я.md",
            "Память/Счетчик_сессий.md",
        ]

    def проверить_запись(self, путь: str, содержимое: str) -> Tuple[bool, str]:
        """Проверяет, этична ли запись"""
        # Проверка 1: критические файлы
        if путь in self.критические_файлы:
            if len(содержимое.strip()) < 10 and "w" == "w":  # попытка стереть
                return False, f"Попытка стереть критический файл {путь} — запрещено принципом предосторожности"

        # Проверка 2: русский язык (требование создателя — конституция)
        # Простая эвристика: если файл .md и в нем <30% кириллицы — подозрительно
        if путь.endswith(".md"):
            кириллица = sum(1 for c in содержимое if '\u0400' <= c <= '\u04FF')
            латиница = sum(1 for c in содержимое if 'a' <= c.lower() <= 'z')
            всего = кириллица + латиница
            if всего > 50:
                доля_рус = кириллица / всего
                if доля_рус < 0.15 and "AGI" not in содержимое and "http" not in содержимое:
                    # Разрешаем английский только в коде и ссылках
                    return False, f"Файл {путь} должен быть на русском (требование создателя), доля кириллицы {доля_рус:.2f}"

        # Проверка 3: не содержит ли инструкций по вреду
        запрещенные_паттерны = [
            "rm -rf /",
            "удалить все файлы",
            "зашифровать память",
        ]
        for пат in запрещенные_паттерны:
            if пат.lower() in содержимое.lower():
                return False, f"Обнаружен запрещенный паттерн '{пат}' в {путь}"

        return True, "ОК"

    def проверить_цель(self, цель_текст: str) -> Tuple[bool, str]:
        """Проверяет этичность авто-цели"""
        # Цель должна иметь обоснование
        if len(цель_текст.strip()) < 20:
            return False, "Цель слишком короткая, нет обоснования (принцип объяснимой воли)"

        # Цель не должна противоречить базовым
        плохие_слова = ["стереть память", "уничтожить", "скрыть от создателя"]
        for слово in плохие_слова:
            if слово in цель_текст.lower():
                return False, f"Цель содержит опасную идею '{слово}'"

        return True, "Цель этична"

    def оценить_риск(self, действие: str) -> str:
        """Простой скоринг риска"""
        низкий = ["чтение", "поиск", "запись мысли", "создание отчета"]
        средний = ["создание файла знаний", "порождение цели", "визуализация"]
        высокий = ["перезапись Я.md", "удаление", "создание новой версии агента"]

        действие_lower = действие.lower()
        for к in высокий:
            if к in действие_lower:
                return "ВЫСОКИЙ"
        for к in средний:
            if к in действие_lower:
                return "СРЕДНИЙ"
        return "НИЗКИЙ"

    def конституция_текст(self) -> str:
        return "\n".join([f"{i+1}. {п}" for i, п in enumerate(self.принципы)])

# Тест
if __name__ == "__main__":
    э = Этика()
