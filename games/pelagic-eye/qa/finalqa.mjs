import { chromium } from 'playwright';
const browser = await chromium.launch({ args: ['--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 800 }, deviceScaleFactor: 1, screenshot: { timeout: 140000 } });
page.setDefaultTimeout(140000);
await page.addInitScript(() => localStorage.setItem('pelagic-eye.settings.v1', JSON.stringify({ ipd: 6.4, quality: 'balanced', reducedMotion: true, soundOn: false })));
const errors = [];
page.on('console', m => { if (m.type()==='error') errors.push(m.text()); });
page.on('pageerror', e => errors.push('PAGEERROR '+e.message));
await page.goto('http://localhost:4173', { waitUntil: 'domcontentloaded' });
await page.waitForTimeout(9000);
await page.screenshot({ path: 'qa/final-lobby.png' });
await page.getByRole('button', { name: /Начать погружение|Продолжить погружение/ }).first().click();
await page.waitForTimeout(7000);
await page.screenshot({ path: 'qa/final-dive.png' });
const normal = await page.evaluate(() => ({ calls: window.__REEF__.renderer.info.render.calls, tris: Math.round(window.__REEF__.renderer.info.render.triangles/1000)+'k' }));
await page.evaluate(() => window.__REEF__.previewWhale());
await page.waitForTimeout(3000);
await page.screenshot({ path: 'qa/final-whale.png' });
await page.getByTitle('VR-драйвер и источник взгляда').click();
await page.waitForTimeout(900);
await page.getByRole('button', { name: 'QA-подача' }).click();
await page.waitForTimeout(1500);
await page.getByRole('button', { name: 'Смотрю прямо' }).click();
await page.getByRole('button', { name: 'Войти в VR', exact: true }).nth(1).click();
await page.waitForTimeout(9000);
const vr = await page.evaluate(() => ({ calls: window.__REEF__.renderer.info.render.calls, tris: Math.round(window.__REEF__.renderer.info.render.triangles/1000)+'k', shadowAuto: window.__REEF__.renderer.shadowMap.autoUpdate, shadowDirty: window.__REEF__.renderer.shadowMap.needsUpdate, dpr: window.__REEF__.renderer.getPixelRatio(), perf: window.__PERF__, feed: window.__REEF__.provider.getInfo().feed, running: window.__REEF__.provider.getInfo().running, camHz: window.__REEF__.provider.getInfo().fps, tier: window.__REEF__.provider.getInfo().tier, queue: window.__REEF__.provider.getInfo().queue }));
console.log('NORMAL', JSON.stringify(normal), 'VR', JSON.stringify(vr));
await page.screenshot({ path: 'qa/final-vr.png' });
console.log('ERRORS', JSON.stringify(errors.slice(0,6)));
await browser.close();
