import { chromium } from 'playwright';
const browser = await chromium.launch({ args: ['--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1100, height: 700 }, deviceScaleFactor: 1, screenshot: { timeout: 120000 } });
page.setDefaultTimeout(120000);
await page.addInitScript(() => localStorage.setItem('pelagic-eye.settings.v1', JSON.stringify({ ipd: 6.4, quality: 'balanced', reducedMotion: false, soundOn: false })));
const errors = [];
page.on('console', m => { if (m.type()==='error') errors.push(m.text()); });
page.on('pageerror', e => errors.push('PAGEERROR '+e.message));
await page.goto('http://localhost:4173', { waitUntil: 'domcontentloaded' });
await page.waitForTimeout(9000);
await page.getByRole('button', { name: /Начать погружение|Продолжить погружение/ }).first().click();
await page.waitForTimeout(5000);
await page.getByTitle('VR-драйвер и источник взгляда').click();
await page.waitForTimeout(1000);
await page.getByRole('button', { name: 'QA-подача' }).click();
await page.waitForTimeout(2000);
await page.getByRole('button', { name: 'Смотрю прямо' }).click();
console.log('entering vr');
await page.getByRole('button', { name: 'Войти в VR', exact: true }).nth(1).click();
await page.waitForTimeout(12000);
const inVr = await page.evaluate(() => ({ perf: window.__PERF__, vrButton: !!document.querySelector('button')?.textContent, modal: !!document.querySelector('input#ipd'), fullscreen: !!document.fullscreenElement }));
console.log('INVR', JSON.stringify(inVr, null, 1));
await page.screenshot({ path: 'qa/vr-fixed.png' });
// portrait rotation should show the rotate hint, not a squeezed stereo pair
await page.setViewportSize({ width: 700, height: 1100 });
await page.waitForTimeout(2500);
await page.screenshot({ path: 'qa/vr-portrait.png' });
await page.setViewportSize({ width: 1100, height: 700 });
await page.waitForTimeout(2500);
await page.getByRole('button', { name: 'Выйти из VR' }).click();
await page.waitForTimeout(3000);
const outVr = await page.evaluate(() => window.__PERF__);
console.log('OUT', JSON.stringify(outVr));
await page.screenshot({ path: 'qa/after-fixed.png' });
console.log('ERRORS', JSON.stringify(errors.slice(0,8)));
await browser.close();
