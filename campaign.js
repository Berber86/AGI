    function cardCraftQuote(input, investment = {}) {
        const state = normalizeState(input);
        const materialQuality = Object.hasOwn(CARD_CRAFT_MATERIALS, investment.materialQuality) ? investment.materialQuality : 'standard';
        const material = CARD_CRAFT_MATERIALS[materialQuality];
        const availableMaterialQualities = getAvailableMaterialQualities(state);
        const materialQualityUnlocked = availableMaterialQualities.includes(materialQuality);
        // Качество ковки = сырьё + мастерство кузнеца (растёт от успешных ковок).
        const qualityScore = Math.min(CARD_RARITY_ODDS.length - 1, material.grade + state.player.craftLevel);
        const baseOdds = CARD_RARITY_ODDS.find(row => qualityScore <= row.maxScore).odds;
        const rareLocked = state.player.era < RARE_CRAFT_MIN_ERA;
        const odds = rareLocked
            ? { ordinary: baseOdds.ordinary, uncommon: baseOdds.uncommon + baseOdds.rare, rare: 0 }
            : { ...baseOdds };
        // Цена растёт с эпохой: славы к поздним эпохам приходит больше, ковка должна оставаться решением.
        const cost = Math.ceil(material.cost * (1 + state.player.era * 0.4));
        return {
            materialQuality, materialLabel: material.label, craftLevel: state.player.craftLevel, craftXp: state.player.craftXp,
            qualityScore, odds, cost, glory: Math.floor(state.player.glory),
            availableMaterialQualities, materialQualityUnlocked,
            unlockText: materialQualityUnlocked ? '' : 'Сырьё «' + material.label + '» откроется в эпоху «' + eraName(material.minEra) + '».',
            rareLocked,
            rareLockText: rareLocked ? 'Редкие карты откроются в эпоху «' + eraName(RARE_CRAFT_MIN_ERA) + '»: нужна бронза.' : '',
            affordable: materialQualityUnlocked && state.player.glory >= cost,
            modelByRarity: { ...CARD_MODEL_BY_RARITY }
        };
    }

    function rollRarity(odds, roll) {
        const value = clampNum(roll, 0, 0.999999, 0.5) * 100;
        if (value < (odds.rare || 0)) return 'rare';
        if (value < (odds.rare || 0) + (odds.uncommon || 0)) return 'uncommon';
        return 'ordinary';
    }

    /**
     * Списывает славу и возвращает редкость с моделью: карта куётся сразу, очередей и дней нет.
     * Здесь же бросается жребий лапы обезьяны (pawRoll) — он не зависит от редкости и до раскрытия
     * карты игроку не показывается: плата становится сюрпризом уже на готовой карте.
     */
    function beginCraft(input, investment = {}, roll = Math.random(), pawRoll = Math.random()) {
        const state = normalizeState(input);
        const quote = cardCraftQuote(state, investment);
        if (!quote.materialQualityUnlocked) return { state, error: quote.unlockText || 'Это сырьё ещё недоступно.' };
        if (state.player.glory < quote.cost) return { state, error: 'Нужно ' + quote.cost + ' славы, а сейчас ' + Math.floor(state.player.glory) + '.' };
        const rarity = rollRarity(quote.odds, roll);
        const paw = rollPawTier(pawRoll);
        state.player.glory -= quote.cost;
        return {
            state, rarity, paw, pawLabel: PAW_TIER_LABELS[paw], cost: quote.cost, modelId: quote.modelByRarity[rarity],
            materialQuality: quote.materialQuality, error: null
        };
    }

    /** Успешная ковка: опыт кузнеца растёт, на уровне CRAFT_XP_PER_LEVEL поднимается мастерство. */
    function completeCraft(input, info = {}) {
        const state = normalizeState(input);
        let leveledUp = false;
        if (state.player.craftLevel < CRAFT_LEVEL_MAX) {
            state.player.craftXp += 1;
            if (state.player.craftXp >= CRAFT_XP_PER_LEVEL) {
                state.player.craftXp = 0;
                state.player.craftLevel += 1;
                leveledUp = true;
            }
        }
        const cardName = info.name ? '«' + String(info.name).slice(0, 60) + '»' : 'карта';
        // Плата попадает в летопись: через пару эпох видно, чем народ заплатил за сильные карты.
        const pawText = typeof info.monkeyPaw === 'string' ? info.monkeyPaw.trim().slice(0, 160) : '';
        chroniclePush(state, 'Кузница: в боевой состав народа вошла ' + cardName + ' (' + (info.rarity || 'ordinary') + ').'
            + (pawText ? ' Лапа обезьяны взяла плату: ' + pawText : ''));
        state.player.campaignNotice = leveledUp
            ? 'Кузнец поднял мастерство до уровня ' + state.player.craftLevel + ': шанс редкой карты вырос.'
            : '';
        return { state, craftLevel: state.player.craftLevel, leveledUp, error: null };
    }

    function failCraft(input, cost, reason) {
        const state = normalizeState(input);
        const refund = clampNum(cost, 0, 9999, 0);
        state.player.glory = clampNum(state.player.glory + refund, 0, 999999, 0);
        state.player.campaignNotice = 'Ковка не удалась' + (reason ? ': ' + String(reason).slice(0, 160) : '') + '. Слава возвращена (' + refund + ').';
        return { state, refund, error: null };
    }

    /* ================= наследие по эпохам ================= */

    function cultureCandidates(state, era) {
        const lineage = Array.isArray(state.player.culturalLineage) ? state.player.culturalLineage : [];
        const pool = HISTORICAL_CULTURES.filter(culture => culture.era === era && !lineage.includes(culture.id));
        if (!pool.length) return [];
        const rng = seededRandom(hashString(state.player.name + state.player.clan + String(era) + 'heritage'));
        const rest = pool.slice();
        const picked = [];
        while (picked.length < CULTURE_CHOICE_SIZE && rest.length) picked.push(rest.splice(Math.floor(rng() * rest.length), 1)[0]);
        return picked;
    }

    function openCultureChoice(state, era) {
        const candidates = cultureCandidates(state, era).map(culture => culture.id);
        state.player.pendingCultureChoice = candidates.length ? { era, candidates } : null;
    }

    function getCultureChoice(input) {
        const state = normalizeState(input);
        const pending = state.player.pendingCultureChoice;
        if (!pending) return null;
        const candidates = pending.candidates.map(id => findCulture(id, pending.era)).filter(Boolean);
        if (!candidates.length) return null;
        const eraRecord = ERA_HISTORICAL[pending.era];
        return {
            era: pending.era,
            eraLabel: eraName(pending.era),
            eraDescription: (eraRecord && eraRecord.desc) || '',
            eraTechnologies: ((eraRecord && eraRecord.tech) || []).slice(),
            current: state.player.historicalCulture,
            candidates: candidates.map(culture => ({ ...culture, combat: describePerks(cultureCombatBonus(culture)) })),
            keep: {
                id: 'keep',
                label: 'Сохранить прежнее наследие',
                description: 'Народ сохраняет наследие «' + ((state.player.historicalCulture && state.player.historicalCulture.name) || 'прежнее') + '» и его боевые бонусы, но перенимает технологии эпохи «' + eraName(pending.era) + '».'
            }
        };
    }

    function chooseCulture(input, choiceId) {
        const state = normalizeState(input);
        const pending = state.player.pendingCultureChoice;
        if (!pending) return { state, error: 'Выбор наследия не открыт. Он появляется при переходе в новую эпоху.' };
        const keep = choiceId === 'keep';
        const culture = keep ? null : findCulture(choiceId, pending.era);
        if (!keep && !culture) return { state, error: 'Такого наследия нет среди предложенных для эпохи «' + eraName(pending.era) + '».' };
        const previous = state.player.historicalCulture;
        if (culture) {
            // Новое наследие может уменьшить лимит колоды: не делаем этого молча, если колода уже собрана.
            const trial = clone(state);
            trial.player.historicalCulture = culture;
            const newLimit = getBattleConfig(trial).deckLimit;
            if (state.player.deckCardIds.length > newLimit) {
                return { state, error: 'Наследие «' + culture.name + '» уменьшит лимит колоды до ' + newLimit + ', а в колоде сейчас ' + state.player.deckCardIds.length + ' карт. Сначала уберите лишние карты во вкладке «Армия».' };
            }
            state.player.historicalCulture = culture;
            if (!state.player.culturalLineage.includes(culture.id)) state.player.culturalLineage.push(culture.id);
            if (state.player.culturalLineage.length > 10) state.player.culturalLineage.shift();
        }
        state.player.pendingCultureChoice = null;
        const technologies = ((ERA_HISTORICAL[pending.era] && ERA_HISTORICAL[pending.era].tech) || []).join(', ');
        const lineageNames = state.player.culturalLineage.map(id => (findCulture(id) || {}).name || id).join(' → ');
        state.player.campaignNotice = culture
            ? 'Наследие принято: ' + culture.name + '. В бою: ' + (describePerks(cultureCombatBonus(culture)).join(', ') || 'без изменений') + '.'
            : 'Прежнее наследие сохранено: ' + ((previous && previous.name) || 'народа') + '. Технологии эпохи «' + eraName(pending.era) + '» доступны.';
        chroniclePush(state, 'Эпоха «' + eraName(pending.era) + '»: '
            + (culture ? 'народ принял наследие ' + culture.name + ' — ' + culture.desc : 'народ сохранил прежнее наследие ' + ((previous && previous.name) || '') + '.')
            + (lineageNames ? ' Линия: ' + lineageNames + '.' : '')
            + (technologies ? ' Технологии эпохи: ' + technologies + '.' : ''));
        return { state, error: null, culture, kept: Boolean(keep) };
    }

    /* ================= состояние ================= */

    function createState() {
        return {
            version: SAVE_VERSION,
            player: {
                name: 'Безымянный народ', clan: 'Медный Ворон', era: 0,
                onboardingComplete: false, seedChoiceId: null, seedLine: '',
                historicalCulture: null, culturalLineage: [],
                glory: GLORY_START, gloryTotal: 0,
                upgrades: emptyPerks(),
                deckCardIds: [],
                craftLevel: 0, craftXp: 0,
                wins: 0, losses: 0, streak: 0, bestStreak: 0, leaderWins: 0, leaderLosses: 0,
                pendingCultureChoice: null,
                chronicle: [],
                campaignNotice: ''
            },
            opponents: createDefaultOpponents()
        };
    }

    /**
     * Приводит сохранение к текущей форме. Старые сейвы кампании (version < 6) не мигрируются:
     * прототип сменил модель целиком — экономика, карта и здания из них не нужны, поэтому
     * несовместимое сохранение заменяется новым состоянием.
     */
    function normalizeState(value) {
        const version = Number(value && value.version);
        if (!value || typeof value !== 'object' || ![6, SAVE_VERSION].includes(version) || !value.player || typeof value.player !== 'object') return createState();
        const state = clone(value);
        state.version = SAVE_VERSION;
        const p = state.player;
        p.name = typeof p.name === 'string' && p.name.trim() ? p.name.trim().slice(0, 60) : 'Безымянный народ';
        p.clan = typeof p.clan === 'string' && p.clan.trim() ? p.clan.trim().slice(0, 60) : 'Медный Ворон';
        p.era = clampInt(p.era, 0, ERAS.length - 1, 0);
        p.onboardingComplete = Boolean(p.onboardingComplete);
        p.seedChoiceId = seedById(p.seedChoiceId) ? p.seedChoiceId : null;
        p.seedLine = typeof p.seedLine === 'string' ? p.seedLine.slice(0, 200) : '';
        p.historicalCulture = findCulture(p.historicalCulture);
        p.culturalLineage = (Array.isArray(p.culturalLineage) ? p.culturalLineage : []).filter(id => findCulture(id)).slice(-10);
        p.glory = clampNum(p.glory, 0, 999999, GLORY_START);
        p.gloryTotal = clampNum(p.gloryTotal, 0, 9999999, p.glory);
        const upgrades = emptyPerks();
        for (const key of COMBAT_KEYS) {
            const def = CAMP_UPGRADES[key];
            upgrades[key] = clampInt(p.upgrades ? p.upgrades[key] : 0, 0, def.max, 0);
        }
        p.upgrades = upgrades;
        const seen = new Set();
        // Предел колоды зависит от эпохи (DECK_CAP_BY_ERA), а не от одной константы: стол растёт,
        // и состав боя растёт вместе с ним. p.era к этому месту уже приведён к диапазону эпох.
        p.deckCardIds = (Array.isArray(p.deckCardIds) ? p.deckCardIds : [])
            .filter(id => typeof id === 'string' && id && !isNpcMilitiaCardId(id) && !seen.has(id) && seen.add(id))
            .slice(0, deckLimits(p.era).cap);
        p.craftLevel = clampInt(p.craftLevel, 0, CRAFT_LEVEL_MAX, 0);
        p.craftXp = clampInt(p.craftXp, 0, CRAFT_XP_PER_LEVEL, 0);
        for (const key of ['wins', 'losses', 'streak', 'bestStreak', 'leaderWins', 'leaderLosses']) p[key] = clampInt(p[key], 0, 999999, 0);
        p.bestStreak = Math.max(p.bestStreak, p.streak);
        p.chronicle = (Array.isArray(p.chronicle) ? p.chronicle : [])
            .filter(entry => entry && typeof entry.text === 'string')
            .map(entry => ({ era: clampInt(entry.era, 0, ERAS.length - 1, 0), text: entry.text.slice(0, 500) }))
            .slice(-20);
        p.campaignNotice = typeof p.campaignNotice === 'string' ? p.campaignNotice : '';
        const pending = p.pendingCultureChoice;
        p.pendingCultureChoice = pending && Number.isFinite(Number(pending.era))
            ? { era: clampInt(pending.era, 0, ERAS.length - 1, 0), candidates: (Array.isArray(pending.candidates) ? pending.candidates : []).filter(id => findCulture(id)).slice(0, CULTURE_CHOICE_SIZE) }
            : null;
        if (p.pendingCultureChoice && !p.pendingCultureChoice.candidates.length) p.pendingCultureChoice = null;
        const defaults = createDefaultOpponents();
        const rawOpponents = Array.isArray(value.opponents) ? value.opponents : [];
        state.opponents = defaults.map(def => {
            const found = rawOpponents.find(item => item && item.id === def.id);
            return found
                ? { ...def, era: clampInt(found.era, 0, BARBARIAN_ERA_CAP, def.era), rating: clampInt(found.rating, 1, 9999, def.rating) }
                : def;
        });
        return state;
    }

    /**
     * Основание народа: два выбора — наследие (культура) и замысел (менталитет). Каждый даёт боевой
     * бонус, вместе они определяют вождя. Никакой экономики и построек: после основания игрок
     * идёт к ИИ-кузнецу за первой картой и выходит на поле только со своей выкованной колодой.
     *
     * Третьего свойства нет: «Происхождение» дублировало замысел — земля «Ямная Степь» и замысел
     * «Стадо и воля» давали один и тот же бонус (+1 к росту энергии), а имя народа земля определяла
     * вместе с культурой. Теперь имя складывается из обоих свойств (peopleName): имён 30, а не шесть,
     * и ни одно поле ввода игроку по-прежнему не нужно (options.name намеренно игнорируется).
     */
    function foundCampaignState(input, options = {}) {
        const state = normalizeState(input);
        if (state.player.onboardingComplete) return { state, error: 'Народ уже основан.' };
        const seed = seedById(options.seedId);
        if (!seed) return { state, error: 'Выберите замысел народа.' };
        const culture = findCulture(options.historicalCultureId, 0);
        if (!culture) return { state, error: 'Выберите наследие эпохи «' + eraName(0) + '».' };
        const name = peopleName(culture, seed);
        state.player.name = name;
        state.player.seedChoiceId = seed.id;
        state.player.seedLine = seed.line || '';
        state.player.historicalCulture = culture;
        state.player.culturalLineage = [culture.id];
        state.player.glory = GLORY_START;
        state.player.gloryTotal = 0;
        state.player.onboardingComplete = true;
        // Игрок начинает без карт: первые боевые карты должны быть выкованы ИИ специально для него.
        state.player.deckCardIds = [];
        const openingHand = getBattleConfig(state).openingHand;
        chroniclePush(state, 'Народ «' + name + '» вышел из культуры ' + culture.name + ' с замыслом «' + seed.name + '»: ' + seed.line + '. Наследие даёт ' + (describePerks(cultureCombatBonus(culture)).join(', ') || 'ничего') + ', замысел — ' + (describePerks(seed.combat || {}).join(', ') || (openingHand > 1 ? 'в начале боя дополнительная карта в руке' : 'ничего')) + '. Боевой набор: ' + (describePerks(combatPerks(state)).join(', ') || 'обычные отряды племени') + '.');
        state.player.campaignNotice = 'Народ основан. Выкуйте первую карту у ИИ-кузнеца: она автоматически попадёт в пустую колоду.';
        return { state, error: null, battle: getBattleConfig(state) };
    }

    function load() {
        try {
            const raw = JSON.parse(root.localStorage.getItem(STORAGE_KEY) || 'null');
            return normalizeState(raw);
        } catch (_) { return createState(); }
    }
    function save(value) {
        try { root.localStorage.setItem(STORAGE_KEY, JSON.stringify(normalizeState(value))); return true; } catch (_) { return false; }
    }

