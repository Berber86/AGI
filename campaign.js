    function buyUpgrade(input, key) {
        const state = normalizeState(input);
        const def = CAMP_UPGRADES[key];
        if (!def) return { state, error: 'Такого улучшения лагеря нет.' };
        const level = upgradeLevel(state, key);
        if (level >= def.max) return { state, error: '«' + def.name + '» уже на пределе.' };
        const cost = def.cost[level];
        if (state.player.glory < cost) return { state, error: 'Нужно ' + cost + ' славы, а сейчас ' + Math.floor(state.player.glory) + '.' };
        // Боевой потолок может быть уже выбран происхождением, замыслом и наследием: не берём
        // славу за улучшение, которое ничего не изменит в бою.
        const trial = clone(state);
        trial.player.upgrades[key] = level + 1;
        if (battleSummary(getBattleConfig(state)) === battleSummary(getBattleConfig(trial))) {
            return { state, error: COMBAT_LABELS[key] + ' уже на боевом пределе — улучшение ничего не даст.' };
        }
        state.player.glory -= cost;
        state.player.upgrades[key] = level + 1;
        chroniclePush(state, 'Лагерь: «' + def.name + '» уровень ' + (level + 1) + ' за ' + cost + ' славы — ' + COMBAT_LABELS[key] + '.');
        state.player.campaignNotice = '«' + def.name + '» ур. ' + (level + 1) + ': ' + COMBAT_LABELS[key] + '.';
        return { state, level: level + 1, cost, error: null };
    }

    /** Сводка лагеря для интерфейса: уровень, цена, эффект и не упёрся ли параметр в потолок. */
    function campSummary(input) {
        const state = normalizeState(input);
        const cfg = getBattleConfig(state);
        return COMBAT_KEYS.map(key => {
            const def = CAMP_UPGRADES[key];
            const level = upgradeLevel(state, key);
            const cost = level >= def.max ? null : def.cost[level];
            const trial = clone(state);
            trial.player.upgrades[key] = Math.min(def.max, level + 1);
            const nextCfg = getBattleConfig(trial);
            return {
                id: key, name: def.name, icon: def.icon, note: def.note, label: COMBAT_LABELS[key],
                level, max: def.max, cost,
                current: cfg[COMBAT_FIELD[key]],
                next: nextCfg[COMBAT_FIELD[key]],
                maxed: level >= def.max,
                atCap: cost !== null && battleSummary(cfg) === battleSummary(nextCfg),
                affordable: cost !== null && state.player.glory >= cost
            };
        });
    }

