    /**
     * Какая стихия культуры во что переходит в бою. Внутри стихии два варианта, и они чередуются
     * по эпохе культуры: иначе все 32 «ремесленные» культуры давали бы один и тот же бонус к атаке,
     * который к тому же упирается в боевой потолок (+2).
     */
    const CULTURE_COMBAT_BY_RESOURCE = {
        materials: ['unit_power', 'energy_cap'],      // камень, медь и бронза: оружие, затем запасы
        knowledge: ['energy_growth', 'fatigue_resist'], // счёт и письмо: темп боя, затем выучка обоза
        food: ['max_hp', 'deck_slots'],               // избыток еды: выносливость вождя, затем войско
        faith: ['fatigue_resist', 'energy_growth']    // обряд и вера: дух обоза, затем подъём отрядов
    };

    // Наследие исторической культуры: боевые ключи из данных берём как есть (у Аккада, например,
    // уже есть deck_slots), а из мирного бонуса выводим один воинский — какой ресурс культура
    // давала, тем и воюет. Так все 63 культуры остаются осмысленным выбором без ручных правок данных.
    function cultureCombatBonus(culture) {
        const perks = emptyPerks();
        const bonus = (culture && culture.bonus) || {};
        addPerks(perks, bonus);
        if (!culture) return perks;
        const shares = {
            materials: clampNum(bonus.materials, 0, 9, 0),
            knowledge: clampNum(bonus.knowledge, 0, 9, 0),
            food: clampNum(bonus.food, 0, 9, 0),
            faith: clampNum(bonus.faith, 0, 9, 0)
        };
        // Приоритет разбора фиксированный: при равных долях (Ямная — еда и металл по 0.2)
        // результат не должен «плавать» между запусками.
        const dominant = Object.keys(shares).sort((a, b) => shares[b] - shares[a])[0];
        if (shares[dominant] <= 0) return perks;
        const variants = CULTURE_COMBAT_BY_RESOURCE[dominant];
        const key = variants[clampInt(culture.era, 0, 99, 0) % variants.length];
        perks[key] += 1;
        return perks;
    }

    function emptyPerks() {
        const perks = {};
        for (const key of COMBAT_KEYS) perks[key] = 0;
        return perks;
    }
    function addPerks(target, bonus) {
        if (!bonus || typeof bonus !== 'object') return target;
        for (const key of COMBAT_KEYS) target[key] += clampInt(bonus[key], 0, 9, 0);
        return target;
    }
    /** Человекочитаемый список боевых бонусов — для карточек выбора и записей летописи. */
    function describePerks(perks) {
        return COMBAT_KEYS
            .filter(key => clampInt(perks && perks[key], 0, 9, 0) > 0)
            .map(key => COMBAT_LABELS[key].replace('+1', '+' + perks[key]));
    }

